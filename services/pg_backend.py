"""Postgres (Supabase) backend for Store.

Store's SQL is written for SQLite. This adapter runs the same statements on
Postgres so the confirmation, idempotency and deletion logic stays identical:
'?' placeholders become '%s', BEGIN IMMEDIATE becomes one global transaction
lock (SQLite serialised all writers the same way), and SQLite PRAGMAs map to
their Postgres equivalents.

Tables live in a private schema (default 'ruamwan'). Supabase exposes only
'public' through its REST API, and anon/authenticated get no privileges here,
so browsers and publishable keys cannot reach health records at all.
"""
import re, threading
from contextlib import contextmanager

SCHEMA_RE = re.compile(r'^[a-z_][a-z0-9_]{0,62}$')

def ddl(schema):
    return f'''
    CREATE SCHEMA IF NOT EXISTS {schema};
    CREATE TABLE IF NOT EXISTS {schema}.records(id TEXT PRIMARY KEY, owner TEXT NOT NULL, kind TEXT NOT NULL, payload TEXT NOT NULL,
        previous_id TEXT REFERENCES {schema}.records(id) DEFERRABLE INITIALLY IMMEDIATE, version INTEGER NOT NULL, created_at TEXT NOT NULL);
    CREATE UNIQUE INDEX IF NOT EXISTS record_successor ON {schema}.records(previous_id) WHERE previous_id IS NOT NULL;
    CREATE INDEX IF NOT EXISTS record_owner_kind ON {schema}.records(owner,kind,created_at);
    CREATE TABLE IF NOT EXISTS {schema}.revisions(owner TEXT PRIMARY KEY, revision INTEGER NOT NULL DEFAULT 0);
    CREATE TABLE IF NOT EXISTS {schema}.plans(id TEXT PRIMARY KEY,owner TEXT NOT NULL,version INTEGER NOT NULL,payload TEXT NOT NULL,input_revision INTEGER NOT NULL,created_at TEXT NOT NULL);
    CREATE INDEX IF NOT EXISTS plan_owner ON {schema}.plans(owner,version);
    CREATE TABLE IF NOT EXISTS {schema}.retries(owner TEXT NOT NULL,key TEXT NOT NULL,digest TEXT NOT NULL,result TEXT NOT NULL,PRIMARY KEY(owner,key));
    CREATE TABLE IF NOT EXISTS {schema}.audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,owner TEXT NOT NULL,event TEXT NOT NULL,object_id TEXT NOT NULL,created_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS {schema}.local_sessions(token_hash TEXT PRIMARY KEY,owner TEXT NOT NULL,csrf TEXT NOT NULL,expires_at DOUBLE PRECISION NOT NULL);
    CREATE TABLE IF NOT EXISTS {schema}.integration_accounts(subject_hash TEXT PRIMARY KEY,owner TEXT UNIQUE NOT NULL);
    CREATE TABLE IF NOT EXISTS {schema}.drafts(id TEXT PRIMARY KEY,owner TEXT NOT NULL,kind TEXT NOT NULL,payload TEXT NOT NULL,created DOUBLE PRECISION NOT NULL);
    CREATE INDEX IF NOT EXISTS draft_owner ON {schema}.drafts(owner,created);
    DO $$ DECLARE t text; BEGIN
      FOREACH t IN ARRAY ARRAY['records','revisions','plans','retries','audit','local_sessions','integration_accounts','drafts'] LOOP
        EXECUTE format('ALTER TABLE {schema}.%I ENABLE ROW LEVEL SECURITY', t);
      END LOOP;
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA {schema} FROM anon, authenticated';
        EXECUTE 'REVOKE ALL ON SCHEMA {schema} FROM anon, authenticated';
      END IF;
    END $$;
    '''

class Row(dict):
    """Behaves like sqlite3.Row: row['col'] and row[0] both work."""
    __slots__ = ('_values',)
    def __init__(self, names, values):
        super().__init__(zip(names, values))
        self._values = values
    def __getitem__(self, key):
        return self._values[key] if isinstance(key, int) else super().__getitem__(key)

def row_factory(cursor):
    names = [d.name for d in cursor.description] if cursor.description else []
    return lambda values: Row(names, values)

class Connection:
    """Accepts Store's SQLite-dialect statements."""
    def __init__(self, conn):
        self._conn = conn
    def execute(self, sql, params=()):
        statement = sql.strip()
        upper = statement.upper()
        if upper == 'BEGIN IMMEDIATE':
            # One writer at a time, exactly like SQLite's database-level write lock.
            return self._conn.execute("SELECT pg_advisory_xact_lock(hashtext('ruamwan_store'))")
        if upper == 'BEGIN':
            return self._conn.execute('SELECT 1')  # already inside a transaction
        if upper == 'PRAGMA DEFER_FOREIGN_KEYS=ON':
            return self._conn.execute('SET CONSTRAINTS ALL DEFERRED')
        if upper.startswith('PRAGMA'):
            return self._conn.execute('SELECT 1')
        statement = statement.replace('INSERT OR IGNORE INTO integration_accounts VALUES(?,?)',
                                      'INSERT INTO integration_accounts VALUES(?,?) ON CONFLICT DO NOTHING')
        # Qualify the upsert column so Postgres never treats it as ambiguous.
        statement = statement.replace('DO UPDATE SET revision=revision+1', 'DO UPDATE SET revision=revisions.revision+1')
        return self._conn.execute(statement.replace('?', '%s'), tuple(params))

_pools = {}
_pools_lock = threading.Lock()

def shared_pool(url, max_size=4):
    """One small pool per database URL for the whole process.

    Supabase's session pooler allows only a limited number of client
    connections, so every Store (and every schema) shares these.
    """
    with _pools_lock:
        pool = _pools.get(url)
        if pool is None or pool.closed:
            from psycopg_pool import ConnectionPool
            # prepare_threshold=None keeps it compatible with Supabase's pooler.
            def configure(conn):
                # Supabase's pooler defaults to extra_float_digits=0, which rounds
                # floats on read; ask for exact round-trip values.
                conn.execute('SET extra_float_digits = 3')
                conn.commit()
            pool = ConnectionPool(url, min_size=1, max_size=max_size, configure=configure,
                                  kwargs={'row_factory': row_factory, 'prepare_threshold': None,
                                          'connect_timeout': 10},
                                  open=True, timeout=30)
            _pools[url] = pool
        return pool

def close_pools():
    with _pools_lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()

class PostgresBackend:
    def __init__(self, url, schema='ruamwan'):
        if not SCHEMA_RE.match(schema):
            raise ValueError('invalid schema name')
        self.schema = schema
        self.pool = shared_pool(url)
        with self.pool.connection() as conn:
            # Creating tables is only needed once; skip it on every cold start after that.
            ready = conn.execute("SELECT to_regclass(%s)", (f'{schema}.drafts',)).fetchone()[0]
            if ready is None:
                conn.execute(ddl(schema))
    @contextmanager
    def connect(self):
        # Commits on success, rolls back on any exception — like sqlite3's context manager.
        with self.pool.connection() as conn:
            # Transaction-scoped, so a shared connection never leaks another schema.
            conn.execute(f'SET LOCAL search_path TO {self.schema}')
            conn.execute('SET LOCAL extra_float_digits = 3')
            yield Connection(conn)
    def close(self):
        pass  # pools are shared; see close_pools()
