// Synthetic live contract check. Does not confirm/save/delete health records.
import {readFile,writeFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import assert from 'node:assert/strict';
import {createRuamwanClient} from '../integration/ruamwan-client.mjs';
const root=new URL('../',import.meta.url);
const apiKey=process.env.RUAMWAN_API_KEY??(await readFile(new URL('.secrets/api-key',root),'utf8')).trim();
const prefix='SOFTWARE-API-CHECK:'+randomUUID();
const a=createRuamwanClient({apiKey,userId:prefix+':a'}),b=createRuamwanClient({apiKey,userId:prefix+':b'});
const report={label:'SOFTWARE LIVE API ONLY; synthetic input, no health confirmations',checks:[]};
const captured_at='2026-10-12T17:02:59Z';
const before=await a.request('records');assert.deepEqual(before.items,[]);
const capture=await a.prepare('กินข้าว',{captured_at,use_model:false});
assert.equal(capture.items[0].record.journal.clock,'00:02:00');
assert.equal(capture.items[0].record.journal.clock_source,'capture_time');
assert.equal(capture.items[0].record.data.occurred_at,'2026-10-13T00:02:00+07:00');
report.checks.push({case:'capture_default',result:capture});
const period=await a.prepare('ตอนเช้ากินข้าว',{captured_at,use_model:false});
assert.equal(period.items[0].record.journal.clock,null);
report.checks.push({case:'period_preserved',result:period});
const clock=await a.prepare('เดิน 16.00',{captured_at,use_model:false});
assert.equal(clock.items[0].record.journal.clock,'16:00:00');assert.equal(clock.items[0].record.data.end,undefined);
report.checks.push({case:'explicit_clock',result:clock});
const draft=await a.chat([{role:'user',content:'กินข้าว'}],{captured_at});
assert.equal(draft.actions[0].records[0].journal.clock,'00:02:00');
report.checks.push({case:'chat_capture',result:draft});
const advice=await a.chat([{role:'user',content:'กินข้าวกับอะไรดี'}]);
assert.equal(advice.status,'meal_ideas');assert.ok(advice.menus.length);assert.ok(!advice.actions?.some(a=>a.type==='records'));
report.checks.push({case:'advice_is_read_only',result:advice});
const preview=await a.preview(capture.items.map(i=>i.record));assert.equal(preview.requires_consent,true);
await assert.rejects(b.confirm(preview.draft_id,randomUUID()),error=>error.status===404);
report.checks.push({case:'other_account_cannot_confirm',passed:true});
const energy=await a.request('food-energy',{method:'POST',body:{name:'ข้าว กับ ไข่พะโล้',components:[{name:'ข้าว',quantity:1,unit:'ทัพพี'},{name:'ไข่พะโล้',quantity:1,unit:'ส่วน'}]}});
assert.deepEqual(energy.kcal,[432.9,432.9]);report.checks.push({case:'composite_energy',kcal:energy.kcal});
assert.deepEqual((await a.request('records')).items,[]);assert.deepEqual((await b.request('records')).items,[]);
const anonymous=await fetch('http://127.0.0.1:8765/api/records');assert.equal(anonymous.status,401);
report.checks.push({case:'anonymous_denied_and_no_health_writes',passed:true});
await writeFile(new URL('reports/api-handoff-live.json',root),JSON.stringify(report,null,2));
console.log(JSON.stringify({checks:report.checks.length,no_health_records_written:true}));
